#!/usr/bin/env node
/**
 * Bump apps/web/public/app-update.json and versioned app icons
 * so installed devices get content + icon updates.
 * Usage: node scripts/bump-app-update.cjs [message]
 */
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const publicDir = path.join(root, 'apps', 'web', 'public');
const file = path.join(publicDir, 'app-update.json');
const swFile = path.join(publicDir, 'sw.js');
const rootPkg = require(path.join(root, 'package.json'));

const current = fs.existsSync(file)
  ? JSON.parse(fs.readFileSync(file, 'utf8'))
  : { version: '1.0.0', notes: [] };

const now = new Date();
const UAE = 'Asia/Dubai';

function uaeParts(d) {
  const parts = new Intl.DateTimeFormat('en-GB', {
    timeZone: UAE,
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
    hour12: false,
  }).formatToParts(d);
  const get = (type) => parts.find((p) => p.type === type)?.value || '00';
  return {
    year: get('year'),
    month: get('month'),
    day: get('day'),
    hour: get('hour'),
    minute: get('minute'),
  };
}

const uaeNow = uaeParts(now);

// Patch is a UAE YYMMDDHHmm stamp so every deploy is newer than the last.
function bumpPatch(v) {
  const parts = String(v || '1.0.0').split('.').map((n) => parseInt(n, 10) || 0);
  while (parts.length < 3) parts.push(0);
  const stamp = Number(
    [
      uaeNow.year.slice(2),
      uaeNow.month,
      uaeNow.day,
      uaeNow.hour,
      uaeNow.minute,
    ].join(''),
  );
  parts[2] = Math.max(parts[2] + 1, stamp);
  return parts.slice(0, 3).join('.');
}

const noteArg =
  process.argv.slice(2).join(' ').trim() ||
  String(process.env.VERCEL_GIT_COMMIT_MESSAGE || '').split('\n')[0].trim();
// A deploy right after a local bump keeps that bump's release note.
const recentRelease =
  Boolean(current.releasedAt) &&
  now.getTime() - new Date(current.releasedAt).getTime() < 2 * 60 * 60 * 1000;
const notes = Array.isArray(current.notes) ? [...current.notes] : [];
if (noteArg) notes.unshift(noteArg);
while (notes.length > 8) notes.pop();

const version = bumpPatch(current.version || rootPkg.version || '1.0.0');
const iconDirRel = `icons/v${version}`;
const iconDir = path.join(publicDir, 'icons', `v${version}`);
fs.mkdirSync(iconDir, { recursive: true });

const iconFiles = [
  'icon-192.png',
  'icon-512.png',
  'apple-touch-icon.png',
  'favicon.png',
  'logo.jpg',
];

for (const name of iconFiles) {
  const src = path.join(publicDir, name);
  if (fs.existsSync(src)) {
    fs.copyFileSync(src, path.join(iconDir, name));
  }
}

const icons = {
  favicon: `/${iconDirRel}/favicon.png`,
  icon192: `/${iconDirRel}/icon-192.png`,
  icon512: `/${iconDirRel}/icon-512.png`,
  apple: `/${iconDirRel}/apple-touch-icon.png`,
  logo: `/${iconDirRel}/logo.jpg`,
};

const next = {
  app: 'CrickHerose',
  version,
  releasedAt: now.toISOString(),
  title: 'CrickHerose update available',
  message:
    noteArg ||
    (recentRelease ? current.message : '') ||
    'New changes from the website are ready. Tap Update now to get them on this device.',
  notes,
  minVersion: current.minVersion || '1.0.0',
  force: Boolean(current.force),
  updateUrl: '/updates',
  iconsUpdated: true,
  icons,
};

fs.writeFileSync(file, JSON.stringify(next, null, 2) + '\n');

// Manifest always points at this version's icons (cache-bust home screen art)
const manifest = {
  id: '/',
  name: 'CrickHerose',
  short_name: 'CrickHerose',
  description: 'CrickHerose — personal records and payment tracking',
  start_url: '/login',
  scope: '/',
  display: 'standalone',
  orientation: 'portrait-primary',
  background_color: '#ffffff',
  theme_color: '#1d4ed8',
  icons: [
    {
      src: icons.icon192,
      sizes: '192x192',
      type: 'image/png',
      purpose: 'any',
    },
    {
      src: icons.icon512,
      sizes: '512x512',
      type: 'image/png',
      purpose: 'any',
    },
    {
      src: icons.icon512,
      sizes: '512x512',
      type: 'image/png',
      purpose: 'maskable',
    },
    {
      src: icons.favicon,
      sizes: '32x32',
      type: 'image/png',
      purpose: 'any',
    },
  ],
};
fs.writeFileSync(
  path.join(publicDir, 'manifest.webmanifest'),
  JSON.stringify(manifest, null, 2) + '\n',
);

// Generated import used by Next layout / client UI
const genTs = `/* auto-generated by scripts/bump-app-update.cjs — do not edit */
export const APP_VERSION = ${JSON.stringify(version)};
export const APP_ICONS = ${JSON.stringify(icons, null, 2)} as const;
export const APP_THEME_COLOR = '#1d4ed8';
`;
fs.writeFileSync(
  path.join(root, 'apps', 'web', 'src', 'lib', 'app-branding.ts'),
  genTs,
);

// Bust service-worker cache name so icon assets are re-fetched
if (fs.existsSync(swFile)) {
  let sw = fs.readFileSync(swFile, 'utf8');
  sw = sw.replace(
    /const CACHE = ['"][^'"]*shell-v[^'"]*['"]/,
    `const CACHE = 'crickherose-shell-v${version.replace(/\./g, '-')}'`,
  );
  fs.writeFileSync(swFile, sw);
}

console.log(
  `Updated app-update.json → v${version} (${uaeNow.day}/${uaeNow.month}/${uaeNow.year} ${uaeNow.hour}:${uaeNow.minute} UAE)`,
);
console.log(`Versioned icons → /${iconDirRel}/`);
